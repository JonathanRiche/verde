pub const HttpConnection = struct {
    url: []u8,
    authorization: []u8,

    pub fn deinit(self: *HttpConnection, allocator: std.mem.Allocator) void {
        allocator.free(self.url);
        allocator.free(self.authorization);
        self.* = undefined;
    }
};

/// Loads the daemon's authenticated loopback endpoint for provider-specific
/// runtime injection. The registration marker remains the opt-in authority.
pub fn loadEndpoint(allocator: std.mem.Allocator) !?Endpoint {
    const pref_path = try platform_paths.sdlPrefPathFallback(allocator, "verde", "Native");
    defer allocator.free(pref_path);
    var threaded: std.Io.Threaded = .init(allocator, .{});
    defer threaded.deinit();
    return mcp_endpoint.load(allocator, threaded.io(), pref_path);
}

pub fn loadHttpConnection(allocator: std.mem.Allocator) !?HttpConnection {
    var endpoint = (try loadEndpoint(allocator)) orelse return null;
    defer endpoint.deinit(allocator);
    const url = try endpoint.urlAlloc(allocator);
    errdefer allocator.free(url);
    return .{
        .url = url,
        .authorization = try endpoint.authorizationAlloc(allocator),
    };
}

const ALL_PROVIDERS = [_]Provider{ .codex, .claude, .cursor, .opencode, .amp, .pi, .fx, .grok };

