fn inspectManagedFileAtHome(
    allocator: std.mem.Allocator,
    home: []const u8,
    relative_path: []const u8,
    marker: []const u8,
) RegistrationStatus {
    const path = configPathAlloc(allocator, home, relative_path) catch return .not_installed;
    defer allocator.free(path);
    var threaded: std.Io.Threaded = .init(allocator, .{});
    defer threaded.deinit();
    const content = readFileIfPresent(allocator, threaded.io(), path) catch return .conflict;
    defer if (content) |bytes| allocator.free(bytes);
    const bytes = content orelse return .not_installed;
    return if (std.mem.startsWith(u8, bytes, marker)) .installed else .conflict;
}

fn removeManagedFileAtHome(
    allocator: std.mem.Allocator,
